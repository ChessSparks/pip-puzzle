// Turn generator output (JSON lines from `generate.mjs --chapter`) into a
// chapter file: dedupe, drop levels with pointless crates, rank by difficulty,
// pick a spread of N from medium to hard, order easy -> hard, write JS.
//
//   node tools/pick-levels.mjs --in a.jsonl,b.jsonl --count 10 --export RIVERLANDS \
//     --title "Riverlands" --names "One,Two,..." --hint "First-level hint" \
//     --spare 1 --out src/core/levels/riverlands.js
import fs from 'node:fs';
import { Level } from '../src/core/Level.js';

const args = process.argv.slice(2);
const flag = (name, dflt) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : dflt;
};
const files = flag('--in', '').split(',').filter(Boolean);
const count = Number(flag('--count', 10));
const names = flag('--names', '').split(',').map((s) => s.trim());
const maxSpare = Number(flag('--spare', 0)); // crates allowed to go unused
const NAMES = { U: 'up', D: 'down', L: 'left', R: 'right' };

// Crates the solution never touches are just clutter (unless they're spares).
function unusedCrates(map, path) {
  const lvl = new Level({ name: 'x', map });
  const used = new Set();
  for (const c of path) {
    const ev = lvl.move(NAMES[c]);
    if (ev?.pushed) used.add(ev.pushed.id);
  }
  return lvl.boxes.length - used.size;
}

const seen = new Set();
let pool = [];
for (const f of files) {
  for (const line of fs.readFileSync(f, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    const rec = JSON.parse(line);
    const key = rec.map.join('|');
    if (seen.has(key)) continue;
    seen.add(key);
    if (unusedCrates(rec.map, rec.path) > maxSpare) continue;
    rec.score = rec.len * Math.log(rec.states);
    pool.push(rec);
  }
}
pool.sort((a, b) => a.score - b.score);
if (pool.length < count) throw new Error(`only ${pool.length} usable candidates`);

// Evenly spaced picks from the 35th percentile up to the hardest (starting
// lower when the pool is small, so no candidate is picked twice).
const picks = [];
const lo = Math.min(Math.floor(pool.length * 0.35), pool.length - count);
for (let i = 0; i < count; i++) {
  const idx = Math.round(lo + ((pool.length - 1 - lo) * i) / Math.max(1, count - 1));
  picks.push(pool[Math.min(idx, pool.length - 1)]);
}

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const body = picks
  .map((p, i) => {
    const lines = [
      '  {',
      `    name: ${q(names[i] ?? `Level ${i + 1}`)},`,
      `    par: ${Math.round(p.len * 1.15) + 1},`,
    ];
    if (i === 0 && flag('--hint', null)) lines.push(`    hint: ${q(flag('--hint'))},`);
    lines.push('    map: [', ...p.map.map((r) => `      ${q(r)},`), '    ],', `    solution: '${p.path}',`, '  },');
    return lines.join('\n');
  })
  .join('\n');

const out = `// Chapter: ${flag('--title', '')}. Generated by tools/generate.mjs and picked by
// tools/pick-levels.mjs (ordered easy -> hard). Hand-edit freely, then re-run
// \`npm run solve -- --optimal\` to refresh solution/par.
export const ${flag('--export', 'LEVELS')} = [
${body}
];
`;
fs.writeFileSync(flag('--out'), out);
console.log(`${flag('--title')}: picked ${count} of ${pool.length} (lengths ${picks.map((p) => p.len).join(', ')})`);
